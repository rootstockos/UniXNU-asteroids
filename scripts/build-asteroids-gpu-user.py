#!/usr/bin/env python3
"""Build the 3a's user-space GPU test (T16) into a GPU addon and an owner trust bundle for the boot payload.

  build-asteroids-gpu-user.py --unixnu PATH --trust-cache ORIGINAL.bundle

Runs on macOS with Xcode's iPhoneOS SDK, after scripts/prepare-asteroids-turnip.py (Turnip for iOS against this repository's ABI).
Output in build/asteroids-gpu-user (ignored):
  NativeTurnipShaders.h      the Turnip smoke shaders (UniXNU drivers/NativeMetal/shaders) as SPIR-V words: glslang, then spirv-val
  asteroidsgpud              package/AsteroidsGpuUserTest.cpp, signed ad hoc with 4 KiB pages and two entitlements
  libvulkan_freedreno.dylib  Turnip, stripped and signed the same way
  *.plist                    three launchd jobs that start the daemon (UniXNU's build-adreno-metal-plugin.py explains the two
                             borrowed job names)
  asteroids-gpu.addon        the NGPUADD2 file for `unixnu build payload --gpu-addon` (scripts/make-gpu-addon.py's format, paths
                             below /private/var/ngpu): bin/asteroidsgpud, bin/libvulkan_freedreno.dylib, daemons/*.plist
  owner-trust.bundle         for `--owner-trust-cache`: one owner module with the two CDHashes, then the original modules of
                             ORIGINAL.bundle byte for byte (UniXNU's make-owner-trust-bundle.py does the same for the full plugin)
shader_tools.py builds glslang and SPIRV-Tools when missing."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import plistlib
import re
import shutil
import struct
import subprocess
import sys
import uuid
import zlib

import shader_tools

DEVICE = Path(__file__).resolve().parents[1]
OUT = DEVICE / 'build/asteroids-gpu-user'
ORIGINAL_TRUST_SHA256 = '7416ca4f8377146626bb284e2133c76bee6cb4e3ee0af5d648b186235a7323a7'
parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
parser.add_argument('--unixnu', type=Path, required=True)
parser.add_argument('--trust-cache', type=Path, required=True, help='the unchanged original static/System trust bundle')
args = parser.parse_args()
ROOT = args.unixnu.resolve()
TURNIP = ROOT / 'build/mesa-tu-ios/src/freedreno/vulkan/libvulkan_freedreno.dylib'
VULKAN_INCLUDE = ROOT / '.cache/mesa-work/include'
METAL = ROOT / 'drivers/NativeMetal'


def run(command, **kw):
    print('+', ' '.join(str(c) for c in command), flush=True)
    return subprocess.run([str(c) for c in command], check=True, **kw)


def cdhash(path):
    detail = subprocess.run(['codesign', '--display', '--verbose=4', str(path)], capture_output=True, text=True, check=True).stderr
    if not re.search(r'^Page size=4096$', detail, re.M):
        sys.exit(f'{path} is not signed with 4 KiB pages')
    return re.search(r'^CDHash=([a-f0-9]{40})$', detail, re.M)[1]


if not TURNIP.is_file():
    sys.exit('Build Turnip first: scripts/prepare-asteroids-turnip.py --unixnu ' + str(ROOT))
original = args.trust_cache.read_bytes()
if hashlib.sha256(original).hexdigest() != ORIGINAL_TRUST_SHA256:
    sys.exit('The trust bundle is not the unchanged original static/System bundle')
shutil.rmtree(OUT, ignore_errors=True)
OUT.mkdir(parents=True)

# 1. The smoke shaders (shader_tools.py builds glslang and spirv-val when missing).
bin_dir = shader_tools.ensure(ROOT)
glslang, spirv_val = bin_dir / 'glslang', bin_dir / 'spirv-val'
lines = ['// Generated by UniXNU-asteroids scripts/build-asteroids-gpu-user.py from UniXNU drivers/NativeMetal/shaders; do not edit.',
         '#pragma once', '#include <stdint.h>']
for source in sorted((METAL / 'shaders').glob('smoke_*')):
    spv = OUT / (source.name + '.spv')
    run([glslang, '-V', '--target-env', 'vulkan1.1', '-o', spv, source], stdout=subprocess.DEVNULL)
    run([spirv_val, '--target-env', 'vulkan1.1', spv])
    data = spv.read_bytes()
    words = struct.unpack('<%dI' % (len(data) // 4), data)
    lines.append('static const uint32_t kSpv_%s[] = {' % source.name.replace('.', '_'))
    lines += ['    ' + ', '.join('0x%08x' % w for w in words[i:i + 8]) + ',' for i in range(0, len(words), 8)]
    lines.append('};')
    spv.unlink()
(OUT / 'NativeTurnipShaders.h').write_text('\n'.join(lines) + '\n')

# 2. The daemon. TurnipReplay.h is on no include path here (AsteroidsGpuUserTest.cpp refuses to build with it).
sdk = subprocess.check_output(['xcrun', '--sdk', 'iphoneos', '--show-sdk-path'], text=True).strip()
base = ['-target', 'arm64-apple-ios17.0', '-isysroot', sdk, '-O2', '-Wall', '-Wextra', '-Werror']
includes = ['-I', DEVICE / 'drivers/Adreno740', '-I', METAL, '-I', ROOT / 'kits/AdrenoPM4', '-I', VULKAN_INCLUDE, '-I', OUT]
pm4 = OUT / 'AdrenoPM4.o'
run(['xcrun', 'clang', *base, '-std=c11', '-c', ROOT / 'kits/AdrenoPM4/AdrenoPM4.c', '-o', pm4])
daemon = OUT / 'asteroidsgpud'
run(['xcrun', 'clang++', *base, '-std=c++17', *includes, DEVICE / 'package/AsteroidsGpuUserTest.cpp', pm4, '-o', daemon])
pm4.unlink()
run(['strip', '-x', daemon])
entitlements = OUT / 'asteroidsgpud-entitlements.plist'
entitlements.write_bytes(plistlib.dumps({'com.apple.private.security.no-container': True,
                                         'com.apple.security.iokit-user-client-class': ['AGXDeviceUserClient']}))
run(['codesign', '--force', '--sign', '-', '--pagesize', '4096', '--identifier', 'org.rootstockos.asteroidsgpud',
     '--entitlements', entitlements, daemon])
signed = plistlib.loads(subprocess.check_output(['codesign', '-d', '--entitlements', ':-', str(daemon)], stderr=subprocess.DEVNULL))
if signed != plistlib.loads(entitlements.read_bytes()):
    sys.exit('The signed entitlement set differs')

# 3. Turnip beside it (NativeTurnipSmoke.h's libraryPath looks next to the executable).
turnip = OUT / 'libvulkan_freedreno.dylib'
shutil.copyfile(TURNIP, turnip)
run(['strip', '-x', turnip])
run(['codesign', '--force', '--sign', '-', '--pagesize', '4096', '--identifier', 'org.rootstockos.turnip', turnip])
for path in (daemon, turnip):
    run(['codesign', '--verify', '--strict', path])
hashes = {'daemon_cdhash': cdhash(daemon), 'turnip_cdhash': cdhash(turnip)}

# 4. launchd jobs: our own label, and the same job under two existing non-essential RunAtLoad names (launchd may enumerate the
#    directory without the overlay's new names; the overlay answers a lookup of an existing name first). The daemon runs once.
program = ['/private/var/ngpu/bin/asteroidsgpud']
jobs = {'org.rootstockos.asteroidsgpud.plist': dict(Label='org.rootstockos.asteroidsgpud', ProgramArguments=program, RunAtLoad=True,
                                                     KeepAlive=False, ThrottleInterval=30, UserName='root', StandardErrorPath='/dev/null'),
        'com.apple.iomfb_fdr_loader.plist': dict(Label='com.apple.iomfb_fdr_loader', ProgramArguments=program, RunAtLoad=True,
                                                  KeepAlive=False, LimitLoadToSessionType='System', ProcessType='Interactive',
                                                  StandardErrorPath='/dev/null'),
        'com.apple.bluetoothd.plist': dict(Label='com.apple.bluetoothd', ProgramArguments=program, RunAtLoad=True, KeepAlive=False,
                                           ProcessType='Interactive', StandardErrorPath='/dev/null')}
for name, job in jobs.items():
    (OUT / name).write_bytes(plistlib.dumps(job, fmt=plistlib.FMT_XML))

# 5. The addon (make-gpu-addon.py's NGPUADD2 layout).
files = [('bin/asteroidsgpud', 0o755, daemon.read_bytes()), ('bin/libvulkan_freedreno.dylib', 0o755, turnip.read_bytes())]
files += [('daemons/' + name, 0o644, (OUT / name).read_bytes()) for name in sorted(jobs)]
pad = lambda data: data + bytes(-len(data) % 8)
body = b''
for name, mode, data in files:
    encoded = name.encode() + b'\0'
    assert len(encoded) <= 160 and '..' not in name.split('/') and not name.startswith('/')
    packed = zlib.compress(data, 9)
    body += struct.pack('<IIQQ', len(encoded), mode, len(data), len(packed)) + pad(encoded) + pad(packed)
addon = OUT / 'asteroids-gpu.addon'
addon.write_bytes(b'NGPUADD2' + struct.pack('<IIQ', len(files), 0, 24 + len(body)) + body)

# 6. The owner trust bundle (make-owner-trust-bundle.py's layout; DarwinBoot wants a module's hashes strictly ascending).
count = struct.unpack_from('<I', original)[0]
assert count == 2
offsets = struct.unpack_from('<2I', original, 4)
originals = [original[offsets[0]:offsets[1]], original[offsets[1]:]]
ordered = sorted(bytes.fromhex(h) for h in hashes.values())
if len(set(ordered)) != len(ordered):
    sys.exit('Duplicate CDHash')
identifier = uuid.uuid5(uuid.NAMESPACE_URL, 'org.rootstockos.asteroids-gpu-user:' + ''.join(h.hex() for h in ordered))
own = struct.pack('<I16sI', 2, identifier.bytes, len(ordered)) + b''.join(h + bytes([2, 0, 0, 0]) for h in ordered)
modules = [own, *originals]
starts, cursor = [], 16
for module in modules:
    starts.append(cursor)
    cursor += len(module)
bundle = struct.pack('<4I', 3, *starts) + b''.join(modules)
assert bundle[starts[1]:] == original[offsets[0]:]
(OUT / 'owner-trust.bundle').write_bytes(bundle)
(OUT / 'trust.json').write_text(json.dumps(dict(hashes, addon_sha256=hashlib.sha256(addon.read_bytes()).hexdigest(),
    owner_trust_sha256=hashlib.sha256(bundle).hexdigest(), shader_tools=shader_tools.TAG,
    purpose='owner-built test daemon and Turnip; trusted only through an extra owner trust module'), indent=2) + '\n')
for name, mode, data in files:
    print(f'{mode:o} {len(data):>10} {name}')
print('PASS: T16 addon', addon, f'({addon.stat().st_size} bytes), owner trust bundle with', ', '.join(hashes.values()))
