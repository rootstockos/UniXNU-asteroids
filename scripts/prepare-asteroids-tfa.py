#!/usr/bin/env python3
"""Generate the speaker amplifiers' settings for the kernel build from the 3a's own NXP container (tfa98xx.cnt).

    prepare-asteroids-tfa.py

Reads .cache/firmware/tfa98xx.cnt (proprietary-files.txt, put there by scripts/extract-files.py) and writes
build/asteroids-tfa/AsteroidsTfaConfig.h for package/AsteroidsTfa9873.c: for each of the two TFA9873 devices ("P" at 0x34, "S" at 0x35)
its bitfield list, then the bitfields the "speaker" profile sets on entry and the ones "Powerdown_All.standby" sets. A bitfield is a
16-bit code (register << 8 | first bit << 4 | width - 1) and a value. The container holds no amplifier firmware for this chip (its patch
is the 42-byte "dummy" one), only these register settings. The header is generated, never committed (SPEC.md section 2)."""
import hashlib
import struct
import sys
from pathlib import Path

# Run from the device repository or from the build tree (as a board.toml recipe): the container is the device repository's, the header
# goes to the tree's build/ (as prepare-asteroids-gmu.py does).
ROOT = Path(__file__).resolve().parents[1]
DEVICE = ROOT if (ROOT / 'board.toml').exists() else (ROOT / 'kits/asteroids').resolve().parent
SOURCE = DEVICE / '.cache/firmware/tfa98xx.cnt'
OUT = ROOT / 'build/asteroids-tfa/AsteroidsTfaConfig.h'
DEVICE_TYPE, PROFILE_TYPE, REGISTER_TYPE, BITFIELD_TYPE, DEFAULT_TYPE = 0, 1, 2, 16, 17
# The devices in amplifier order (AsteroidsTfa9873.h: 0 = P at 0x34, 1 = S at 0x35) and the profiles the driver uses.
DEVICES, SPEAKER, STANDBY = ('P', 'S'), 'speaker', 'Powerdown_All.standby'


def fail(why):
    sys.exit('prepare-asteroids-tfa: ' + why)


def desc(word):
    return word & 0xffffff, word >> 24


def string_at(data, offset):
    return data[offset:data.index(b'\0', offset)].decode('ascii', 'replace')


def bitfields(data, words, stop_at_default):
    """The bitfield items of a list, in order, up to its first non-register item (devices) or its "default" marker (profiles)."""
    out = []
    for word in words:
        offset, kind = desc(word)
        if kind == BITFIELD_TYPE:
            value, field = struct.unpack_from('<HH', data, offset)
            out.append((field, value))
        elif kind == REGISTER_TYPE:
            fail('register items are not handled (none were in the 3a container)')
        elif kind == DEFAULT_TYPE and stop_at_default:
            break
        elif not stop_at_default:
            break
    return out


def main():
    if not SOURCE.is_file():
        fail(f'{SOURCE} is missing: run scripts/extract-files.py')
    data = SOURCE.read_bytes()
    digest = hashlib.sha256(data).hexdigest()
    if data[0:2] != b'PM' or struct.unpack_from('<I', data, 6)[0] != len(data):
        fail('not a TFA container')
    kind = data[32:40].split(b'\0')[0].decode()
    if not kind.startswith('9873'):
        fail(f'container is for {kind}, not the TFA9873')
    ndev = struct.unpack_from('<H', data, 40)[0]
    devices, profiles = {}, {}
    for i in range(ndev):
        offset, _ = desc(struct.unpack_from('<I', data, 46 + 4 * i)[0])
        length, bus, address, _func, _devid, name = struct.unpack_from('<BBBBII', data, offset)
        words = [struct.unpack_from('<I', data, offset + 12 + 4 * j)[0] for j in range(length)]
        devices[string_at(data, desc(name)[0])] = (address, bitfields(data, words, False))
        for word in words:
            if desc(word)[1] == PROFILE_TYPE:
                p = desc(word)[0]
                head, pname = struct.unpack_from('<II', data, p)
                pwords = [struct.unpack_from('<I', data, p + 8 + 4 * k)[0] for k in range(head & 0xff)]
                profiles[string_at(data, desc(pname)[0])] = bitfields(data, pwords, True)
    for name in DEVICES:
        if name not in devices:
            fail(f'device {name} missing')
    for name in (SPEAKER, STANDBY):
        if name not in profiles:
            fail(f'profile {name} missing')

    def table(symbol, items):
        return (f'static const uint16_t {symbol}[{len(items)}][2] = {{\n' +
                '\n'.join(f'    {{0x{f:04x}, 0x{v:04x}}},' for f, v in items) + '\n};\n')

    text = [f'/* From tfa98xx.cnt (sha256 {digest}), proprietary-files.txt. Generated by scripts/prepare-asteroids-tfa.py for the kernel\n'
            f' * build; never commit. Bitfield codes: register << 8 | first bit << 4 | width - 1. */\n',
            '#include <stdint.h>\n',
            f'#define TFA_CFG_ADDRESS_P 0x{devices["P"][0]:02x}\n#define TFA_CFG_ADDRESS_S 0x{devices["S"][0]:02x}\n',
            table('tfa_cfg_device_p', devices['P'][1]), table('tfa_cfg_device_s', devices['S'][1]),
            table('tfa_cfg_speaker', profiles[SPEAKER]), table('tfa_cfg_standby', profiles[STANDBY])]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(''.join(text))
    print(f'{OUT}: P {len(devices["P"][1])} S {len(devices["S"][1])} speaker {len(profiles[SPEAKER])} '
          f'standby {len(profiles[STANDBY])} bitfields')


if __name__ == '__main__':
    main()
